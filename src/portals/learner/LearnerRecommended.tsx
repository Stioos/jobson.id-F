"use client";

import * as React from "react";
import { useNav } from "@/lib/store";
import { trainingCourses, learnerCourseEnrollments } from "@/lib/lms-data";
import { lmsAiService } from "@/lib/mock-api";
import type { TrainingCourse } from "@/lib/types";
import { PageHeader, SectionCard, EmptyState } from "@/components/common";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import {
  MatchScore,
} from "@/components/common";
import {
  LearnerDisclaimer, SimulatedAiBadge, ThumbnailIcon, DifficultyBadge,
  StarRating, durationLabel, LEARNER_ID,
} from "./_shared";
import { formatCurrency } from "@/lib/format";
import { toast } from "sonner";
import {
  Sparkles, RefreshCw, ShoppingCart, BookOpen, ArrowRight, Users, Lightbulb,
} from "lucide-react";

interface Recommendation {
  course: TrainingCourse;
  reason: string;
  matchScore: number;
}

const FALLBACK_REASONS: Record<string, string> = {
  tc_c001: "Builds on your verified React & TypeScript skills",
  tc_c002: "Pairs well with your completed DevOps foundation",
  tc_c003: "Recommended for senior IC → manager transition",
  tc_c004: "High demand skill — matches your career goal",
  tc_c005: "Compliance essential — pairs with your DPDP cert",
  tc_c006: "Adjacent skill to round out your profile",
  tc_c007: "Mandatory security awareness — pairs with your DPDP cert",
  tc_c008: "Stretch goal for senior leadership track",
};

export function LearnerRecommended() {
  const { navigate } = useNav();
  const [loading, setLoading] = React.useState(true);
  const [recs, setRecs] = React.useState<Recommendation[]>([]);
  const [seed, setSeed] = React.useState(0);

  React.useEffect(() => {
    let cancelled = false;
    setLoading(true);
    lmsAiService.recommendCourses(LEARNER_ID).then((res) => {
      if (cancelled) return;
      const mapped: Recommendation[] = res.recommendations.map((r: { course: TrainingCourse; reason: string; matchScore: number }) => ({
        course: r.course,
        reason: FALLBACK_REASONS[r.course.id] ?? r.reason,
        matchScore: r.matchScore,
      }));
      setRecs(mapped);
      setLoading(false);
    });
    return () => {
      cancelled = true;
    };
  }, [seed]);

  function refresh() {
    setSeed((s) => s + 1);
    toast.info("Refreshing recommendations…");
  }

  function enroll(c: TrainingCourse) {
    toast.success(`Enrolled in "${c.name}"`, {
      description: `Added to My Learning · ${formatCurrency(c.price, c.currency)}`,
    });
    setTimeout(() => navigate("candidate", `my-learning/${c.id}`), 800);
  }

  const myEnrollmentIds = learnerCourseEnrollments
    .filter((e) => e.learnerId === LEARNER_ID)
    .map((e) => e.courseId);

  // "Learners like you also took" — courses completed by other learners with similar paths
  const similarLearners = ["tc_c003", "tc_c004", "tc_c006", "tc_c008"]
    .map((id) => trainingCourses.find((c) => c.id === id))
    .filter((c): c is TrainingCourse => !!c && !myEnrollmentIds.includes(c.id))
    .slice(0, 3);

  return (
    <div className="space-y-6">
      <PageHeader
        title="Recommended for you"
        description="AI-matched courses based on your skills, goals, and learning history."
        icon={<Sparkles className="h-5 w-5" />}
        actions={[
          { label: "Refresh", icon: "RefreshCw", variant: "outline", onClick: refresh },
        ]}
      />

      <div className="flex items-center justify-between gap-2 rounded-lg border border-amber-500/30 bg-amber-500/5 p-3 text-xs">
        <div className="flex items-center gap-2">
          <SimulatedAiBadge />
          <span className="text-muted-foreground">
            Recommendations are generated by a simulated AI model for demo purposes.
          </span>
        </div>
      </div>

      <LearnerDisclaimer />

      {loading ? (
        <div className="grid gap-4 lg:grid-cols-2">
          {[1, 2, 3, 4].map((i) => (
            <div key={i} className="space-y-3 rounded-xl border p-4">
              <div className="flex items-center gap-3">
                <Skeleton className="h-12 w-12 rounded-xl" />
                <div className="flex-1 space-y-2">
                  <Skeleton className="h-4 w-3/4" />
                  <Skeleton className="h-3 w-1/2" />
                </div>
                <Skeleton className="h-9 w-9 rounded-full" />
              </div>
              <Skeleton className="h-3 w-full" />
              <div className="flex gap-2">
                <Skeleton className="h-8 w-24" />
                <Skeleton className="h-8 w-24" />
              </div>
            </div>
          ))}
        </div>
      ) : recs.length === 0 ? (
        <EmptyState
          icon={<Sparkles className="h-5 w-5" />}
          title="No recommendations yet"
          description="Complete a course or update your profile to get personalized recommendations."
        />
      ) : (
        <div className="grid gap-4 lg:grid-cols-2">
          {recs.map((rec) => {
            const c = rec.course;
            const enrolled = myEnrollmentIds.includes(c.id);
            return (
              <div key={c.id} className="flex flex-col gap-3 rounded-xl border p-4 transition hover:shadow-sm">
                <div className="flex items-start gap-3">
                  <ThumbnailIcon color={c.thumbnailColor} icon={c.thumbnailIcon} size="md" />
                  <div className="min-w-0 flex-1">
                    <div className="mb-1 flex flex-wrap items-center gap-2">
                      <Badge variant="secondary" className="text-[10px]">{c.category}</Badge>
                      <DifficultyBadge level={c.difficulty} />
                    </div>
                    <button
                      onClick={() => navigate("candidate", `catalog/${c.id}`)}
                      className="line-clamp-2 text-left text-sm font-semibold hover:text-brand"
                    >
                      {c.name}
                    </button>
                    <p className="mt-1 text-xs text-muted-foreground">{c.instructorName}</p>
                  </div>
                  <MatchScore score={rec.matchScore} />
                </div>

                {/* Reason */}
                <div className="rounded-lg border bg-amber-500/5 p-2.5 text-xs">
                  <p className="flex items-start gap-1.5">
                    <Lightbulb className="mt-0.5 h-3.5 w-3.5 shrink-0 text-amber-600 dark:text-amber-400" />
                    <span>{rec.reason}</span>
                  </p>
                </div>

                {/* Skills matched */}
                <div className="flex flex-wrap items-center gap-1">
                  <span className="text-[10px] uppercase tracking-wide text-muted-foreground">Matched skills:</span>
                  {c.skills.slice(0, 4).map((s) => (
                    <Badge key={s} variant="outline" className="text-[10px]">{s}</Badge>
                  ))}
                </div>

                {/* Meta + actions */}
                <div className="mt-auto flex items-center justify-between border-t pt-3">
                  <div className="flex items-center gap-3 text-xs text-muted-foreground">
                    <StarRating value={c.rating} count={c.ratingCount} />
                    <span className="flex items-center gap-1">
                      <Users className="h-3 w-3" /> {c.enrollments.toLocaleString("en-IN")}
                    </span>
                    <span className="font-semibold text-brand">{formatCurrency(c.price, c.currency)}</span>
                  </div>
                  <div className="flex items-center gap-1">
                    <Button
                      variant="outline"
                      size="sm"
                      onClick={() => navigate("candidate", `catalog/${c.id}`)}
                    >
                      <BookOpen className="mr-1 h-3.5 w-3.5" /> View
                    </Button>
                    <Button
                      size="sm"
                      onClick={() => (enrolled ? navigate("candidate", `my-learning/${c.id}`) : enroll(c))}
                    >
                      {enrolled ? (
                        <>
                          <ArrowRight className="mr-1 h-3.5 w-3.5" /> Resume
                        </>
                      ) : (
                        <>
                          <ShoppingCart className="mr-1 h-3.5 w-3.5" /> Enroll
                        </>
                      )}
                    </Button>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Learners like you also took */}
      <SectionCard
        title="Learners like you also took"
        description="Popular among learners with a similar skill profile"
      >
        <div className="grid gap-3 sm:grid-cols-3">
          {similarLearners.map((c) => (
            <button
              key={c.id}
              onClick={() => navigate("candidate", `catalog/${c.id}`)}
              className="group rounded-lg border p-3 text-left transition hover:border-brand/40 hover:shadow-sm"
            >
              <div className="mb-2 flex items-center gap-2">
                <ThumbnailIcon color={c.thumbnailColor} icon={c.thumbnailIcon} size="sm" />
                <DifficultyBadge level={c.difficulty} />
              </div>
              <p className="line-clamp-2 text-sm font-semibold">{c.name}</p>
              <div className="mt-2 flex items-center justify-between text-xs">
                <StarRating value={c.rating} />
                <span className="font-semibold text-brand">{formatCurrency(c.price, c.currency)}</span>
              </div>
            </button>
          ))}
        </div>
      </SectionCard>
    </div>
  );
}
